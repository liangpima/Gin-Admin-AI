package common

import "strings"

// EscapeLike 转义 LIKE 模式中的通配符，使输入按**字面量**参与匹配。
//
// 背景：全仓有 18 处 `"%"+input+"%"` 直接拼进 LIKE 模式。参数是绑定的，
// 所以这不是 SQL 注入；但用户输入里的 `%` 与 `_` 会**改写匹配语义**：
//   - 搜 `%%%` 等价于「匹配全部记录」—— 攻击者据此探测数据量，
//     也让本应受限的模糊搜索变成全表扫描（大表上是可观的资源消耗）
//   - 搜 `a_c` 会把 `abc`、`a1c` 也算命中，用户看到的结果与预期不符
//
// 需要转义的三个字符（缺一不可）：
//
//	\  → \\    自身是转义符，不转义会让输入 `\%` 变成「字面量 %」，
//	           从而绕过对 % 的处理
//	%  → \%
//	_  → \_
//
// 用 strings.NewReplacer 做**单趟**替换：它不会二次扫描已替换的内容，
// 因此不存在「先处理 % 再把刚插入的 \ 又转义一遍」的问题。
// 若改用链式 ReplaceAll 实现，则必须先替换 `\`，否则结果会错。
//
// 转义符依赖 MySQL 的默认值 `\`（本项目生产库为 MySQL，未改 sql_mode）。
// 刻意不追加 `ESCAPE '\'` 子句：MySQL 的字符串字面量里 `'\'` 是「转义后的引号」，
// 会直接导致语法错误；而 SQLite 恰好相反（反斜杠无特殊含义，需要显式 ESCAPE）。
// 两边写法不兼容，写死任一种都会让另一边的行为与预期不符。
//
// 副作用（有意的取舍）：测试环境用 SQLite，它不认反斜杠转义，
// 于是转义后的模式会**少匹配**（`\%` 被当成字面量 `\%`）而不是多匹配 ——
// 失败方向是安全的那一侧，生产（MySQL）下才是精确的字面量匹配。
func EscapeLike(s string) string {
	if !strings.ContainsAny(s, `\%_`) {
		return s
	}
	return strings.NewReplacer(`\`, `\\`, `%`, `\%`, `_`, `\_`).Replace(s)
}
